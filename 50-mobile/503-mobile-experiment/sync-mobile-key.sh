#!/usr/bin/env bash
# Write the environment mobile key to gitignored Android and iOS config files.
# Mobile SDK credentials: https://launchdarkly.com/docs/home/account/environment/settings

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ANDROID_PROPS="${SCRIPT_DIR}/android/local.properties"
IOS_XCCONFIG="${SCRIPT_DIR}/ios/LDMobileKey.xcconfig"

if [[ -z "${LD_MOBILE_KEY:-}" ]]; then
  echo "error: LD_MOBILE_KEY is required" >&2
  echo 'export LD_MOBILE_KEY="mob-..."  # mobile key, never a server SDK key' >&2
  exit 1
fi

key="$LD_MOBILE_KEY"
if [[ "$key" == sdk-* ]]; then
  echo "error: LD_MOBILE_KEY looks like a server SDK key; use the environment mobile key." >&2
  exit 1
elif [[ "$key" != mob-* ]]; then
  echo "warning: LD_MOBILE_KEY does not start with mob-; continuing." >&2
fi

mkdir -p "$(dirname "$ANDROID_PROPS")" "$(dirname "$IOS_XCCONFIG")"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
if [[ -f "$ANDROID_PROPS" ]]; then
  grep -v '^ld\.mobile\.key=' "$ANDROID_PROPS" >"$tmp" || true
fi
printf 'ld.mobile.key=%s\n' "$key" >>"$tmp"
mv "$tmp" "$ANDROID_PROPS"

cat >"$IOS_XCCONFIG" <<EOF
// Generated by sync-mobile-key.sh — gitignored; do not commit.
LD_MOBILE_KEY = ${key}
EOF

echo "Wrote android/local.properties and ios/LDMobileKey.xcconfig without printing the key."
